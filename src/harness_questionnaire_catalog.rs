pub(crate) fn format_questionnaire() -> String {
    use std::fmt::Write;
    let mut text = String::from(
        "CA behavior questionnaire\nSignals guide investigation; they do not prove a behavioral failure or improvement.\n",
    );
    let mut previous_domain = "";
    for question in QUESTIONS {
        if question.domain != previous_domain {
            let _ = writeln!(text, "\n{}", question.domain);
            previous_domain = question.domain;
        }
        let _ = writeln!(
            text,
            "\n{} (weight {}): {}\n  Evidence: {}\n  Improvement objective: {}",
            question.id,
            question.weight,
            question.question,
            question.evidence,
            question.improvement,
        );
    }
    text
}
