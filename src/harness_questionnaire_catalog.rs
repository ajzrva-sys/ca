//! Host-owned questions about durable agent behavior. Outcome signals identify
//! where to investigate; they do not independently verify a question's answer.
use serde::{Deserialize, Serialize};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
